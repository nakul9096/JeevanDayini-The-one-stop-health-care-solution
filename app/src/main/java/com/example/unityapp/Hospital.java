package com.example.unityapp;
public class Hospital {
    private String key;
    private String adminType;
    private String address;
    private String bdf;
    private String email;
    private String imageUrlHorizontal1;
    private String imageUrlHorizontal2;
    private String mapUrl;
    private String name;
    private String ratings;
    private String selectedCity;
    private String selectedState;
    private String status;

    public Hospital() {}

    // Getters and Setters
    public String getKey() { return key; }
    public void setKey(String key) { this.key = key; }
    public String getAdminType() { return adminType; }
    public void setAdminType(String adminType) { this.adminType = adminType; }
    public String getAddress() { return address; }
    public void setAddress(String address) { this.address = address; }
    public String getBdf() { return bdf; }
    public void setBdf(String bdf) { this.bdf = bdf; }
    public String getEmail() { return email; }
    public void setEmail(String email) { this.email = email; }
    public String getImageUrlHorizontal1() { return imageUrlHorizontal1; }
    public void setImageUrlHorizontal1(String imageUrlHorizontal1) { this.imageUrlHorizontal1 = imageUrlHorizontal1; }
    public String getImageUrlHorizontal2() { return imageUrlHorizontal2; }
    public void setImageUrlHorizontal2(String imageUrlHorizontal2) { this.imageUrlHorizontal2 = imageUrlHorizontal2; }
    public String getMapUrl() { return mapUrl; }
    public void setMapUrl(String mapUrl) { this.mapUrl = mapUrl; }
    public String getName() { return name; }
    public void setName(String name) { this.name = name; }
    public String getRatings() { return ratings; }
    public void setRatings(String ratings) { this.ratings = ratings; }
    public String getSelectedCity() { return selectedCity; }
    public void setSelectedCity(String selectedCity) { this.selectedCity = selectedCity; }
    public String getSelectedState() { return selectedState; }
    public void setSelectedState(String selectedState) { this.selectedState = selectedState; }
    public String getStatus() { return status; }
    public void setStatus(String status) { this.status = status; }
}